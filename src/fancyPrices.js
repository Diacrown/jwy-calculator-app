export const FANCY_GRADE_ORDER = ["TW VS", "TW SI3", "TW SI"];

// Grades that have a price for this size code (empty when the size is not a priced fancy size).
export function fancyGradesFor(table, code) {
  const row = table && table[code];
  if (!row) return [];
  return Object.keys(row).filter((g) => row[g] > 0).sort((a, b) => FANCY_GRADE_ORDER.indexOf(a) - FANCY_GRADE_ORDER.indexOf(b));
}
